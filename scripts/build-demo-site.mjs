#!/usr/bin/env node
/**
 * Build every enabled demo view (libs/demo-switcher/src/views.js) in Vite demo mode
 * into ONE static site:
 *
 *   dist/demo-site/            View 1 (apps/web, base /)
 *   dist/demo-site/v2/         View 2 (apps/web-v2, base /v2/)
 *   dist/demo-site/_redirects  SPA rules for every view, then App 1's own rules
 *   dist/demo-site/robots.txt  Disallow all (demo site must not be indexed)
 *
 * Production App 1 is unaffected: it keeps building to apps/web/dist with `npm run build:web`,
 * without the switcher. Usage: `npm run build:demo` (from the repo root).
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { enabledViews } from '../libs/demo-switcher/src/views.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outRoot = path.join(root, 'dist', 'demo-site');
const views = enabledViews();

function viewOutDir(view) {
  const segments = view.basePath.split('/').filter(Boolean);
  return path.join(outRoot, ...segments);
}

// Root view first: its build empties the whole folder; nested views are written afterwards.
const ordered = [...views].sort((a, b) => a.basePath.length - b.basePath.length);
if (ordered[0]?.basePath !== '/') {
  console.error('A view with basePath "/" is required (the existing website).');
  process.exit(1);
}

rmSync(outRoot, { recursive: true, force: true });
for (const view of ordered) {
  const cwd = path.join(root, view.appDir);
  const outDir = viewOutDir(view);
  console.log(`\n▶ ${view.label} (${view.appDir}) → ${path.relative(root, outDir) || '.'}`);
  const result = spawnSync('npx', ['vite', 'build', '--mode', 'demo', '--outDir', outDir, '--emptyOutDir'], {
    cwd,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  if (result.status !== 0) {
    console.error(`Build failed for ${view.id}`);
    process.exit(result.status ?? 1);
  }
}

// Redirect rules: nested views first (longest base first), then the root view's own file.
const rootRedirectsPath = path.join(outRoot, '_redirects');
const rootRules = existsSync(rootRedirectsPath) ? readFileSync(rootRedirectsPath, 'utf8').trim() : '/* /index.html 200';
const nested = ordered.filter((view) => view.basePath !== '/').sort((a, b) => b.basePath.length - a.basePath.length);
const viewRules = nested.flatMap((view) => {
  const base = view.basePath.replace(/\/$/, '');
  return [`${base} ${base}/${view.languages[0]} 302`, `${base}/* ${base}/index.html 200`];
});
writeFileSync(rootRedirectsPath, [
  '# Generated by scripts/build-demo-site.mjs: demo views first, then the existing website rules.',
  ...viewRules,
  rootRules,
  '',
].join('\n'));

writeFileSync(path.join(outRoot, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
rmSync(path.join(outRoot, 'sitemap.xml'), { force: true });

console.log(`\n✔ Demo site ready in ${path.relative(root, outRoot)} (${views.map((view) => `${view.label} at ${view.basePath}`).join(', ')}).`);
console.log('  Preview locally with: npm run serve:demo');
